import functools

import numpy as np

from ipi.utils import depend
from ipi.utils.array_backend import backend, device, jit
from ipi.utils.messages import verbosity, warning

__all__ = ["JitError", "split", "eager", "compiled"]

# eager calls before the recording, which fill the caches of the depend objects
WARMUP_CALLS = 2


class JitError(RuntimeError):
    """Raised when a function cannot be compiled and replayed."""


def split(obj):
    """Allows the recording of a function, if any, to be interrupted at this
    point, which is described by `obj` (see `GraphReplay.split`)."""

    if depend._recorder is not None:
        depend._recorder.split(obj)


def eager(func, *args):
    """Returns func(*args). While a function is recorded as CUDA graphs, the
    call is not recorded, and it is made again at each replay: `func` must
    return a list (possibly of lists), whose tensors are then copied into the
    ones returned while recording, and whose other items replace theirs."""

    if depend._recorder is None:
        return func(*args)
    return depend._recorder.call(func, *args)


def compiled(func):
    """Decorates a function of arrays, which is compiled with torch.compile when
    the steps are replayed as CUDA graphs: its operations are then merged in
    fewer kernels, which are faster to replay. It is called as it is otherwise,
    or if torch.compile is not available for the Python version or the GPU.
    As the compiled function is specific to the values of the Python scalars it
    is given, its arguments should be arrays."""

    @functools.wraps(func)
    def wrapper(*args):
        if jit() and backend() == "torch":
            return _compiled(func)(*args)
        return func(*args)

    return wrapper


@functools.cache
def _compiled(func):
    """Returns `func` compiled with torch.compile, or `func` if it cannot be
    compiled."""

    import torch

    # the kernels are generated by Triton, which needs a GPU of compute
    # capability 7.0 or newer
    if torch.cuda.get_device_capability(device()) < (7, 0):
        warning(
            f"{func.__name__} is not compiled: the GPU is too old for torch.compile",
            verbosity.low,
        )
        return func
    try:
        return torch.compile(func, fullgraph=True, dynamic=False)
    except RuntimeError as err:
        warning(f"{func.__name__} is not compiled: {err}", verbosity.low)
        return func


class _Recorder:
    """Notified by the depend objects of their operations while a function is
    recorded, see `depend.set_recorder`."""

    def __init__(self, replay):
        self.split = replay.split
        self.call = replay.call
        # the lists returned by eager calls, which are kept up to date
        self.outputs = set()
        self.reset()

    def reset(self):
        # depend objects read before being modified, keyed by their status
        self.inputs = {}
        # statuses of the objects written or recomputed, and of their dependants
        self.written = set()
        self.statuses = set()
        self.synchros = set()
        # scalars written or recomputed, and host arrays that are written
        self.values = {}
        self.host_writes = set()

    def read(self, dep):
        status = dep._status
        if status in self.written or status in self.inputs:
            return
        dep = dep._root()
        value = dep._wvalue if isinstance(dep, depend.depend_array) else dep._value
        copy = value.copy() if isinstance(value, np.ndarray) else None
        self.inputs[status] = (dep, value, copy)

    def tainted(self, dep, taintme):
        self.statuses.add(dep._status)
        if not taintme:
            self.written.add(dep._status)
            if isinstance(dep, depend.depend_value):
                self.values[dep] = None
            elif isinstance(dep._root()._wvalue, np.ndarray):
                self.host_writes.add(dep._name)

    def synchronized(self, synchro):
        self.synchros.add(synchro)

    def add_outputs(self, outputs):
        if isinstance(outputs, list):
            self.outputs.add(id(outputs))
            for item in outputs:
                self.add_outputs(item)

    def final_state(self):
        """Returns the taint status of all the objects that may have been
        tainted, i.e. of the dependants of those that have been modified, and
        the state of their synchronizations."""

        statuses, synchros = set(), set(self.synchros)
        stack = list(self.statuses)
        while stack:
            status = stack.pop()
            if status in statuses:
                continue
            statuses.add(status)
            for item in status.dependants:
                item = item()
                if item is not None:
                    stack.append(item._status)
            if status.synchro is not None:
                synchros.add(status.synchro)
                stack.extend(peer._status for peer in status.synchro.peers)

        return (
            [(status, status.tainted) for status in statuses],
            [(synchro, synchro.manual) for synchro in synchros],
        )
